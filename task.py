# Create a new Document
doc = Document()

# Set default font to Songti (standard for Chinese documents)
style = doc.styles['Normal']
style.font.name = 'Times New Roman'
style.element.rPr.rFonts.set(qn('w:eastAsia'), '宋体')
style.font.size = Pt(12)
# ✅ 优化：设置默认段落行距，避免文字拥挤
style.paragraph_format.line_spacing = 1.5

def add_lesson_plan(doc, lesson_data):
    # Lesson Title
    p = doc.add_heading(f"第{lesson_data['num']}课 {lesson_data['title']}", level=1)
    p.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
    
    # Standard Sections
    sections = [
        ("一、教材内容分析", lesson_data['textbook']),
        ("二、教学对象分析", lesson_data['student']),
        ("三、教学目标", lesson_data['objectives']),
        ("四、重点与难点", f"教学重点：{lesson_data['key_points']}\n教学难点：{lesson_data['difficulties']}"),
        ("五、设计思路和教学策略", lesson_data['strategy']),
        ("六、教学资源", lesson_data['resources']),
        ("七、课时教学过程", "") 
    ]
    
    for sec_title, sec_content in sections:
        h = doc.add_paragraph()
        run = h.add_run(sec_title)
        run.bold = True
        run.font.size = Pt(14)
        if sec_content:
            p = doc.add_paragraph(sec_content)
            p.paragraph_format.first_line_indent = Pt(24)  # 首行缩进2字符
            p.paragraph_format.line_spacing = 1.5

    # Process Table
    table = doc.add_table(rows=1, cols=4)
    table.style = 'Table Grid'  # 带边框表格样式
    table.autofit = False 
    
    # Set column widths (精准宽度，适配A4纸)
    widths = [Inches(0.8), Inches(2.2), Inches(2.2), Inches(1.2)]
    hdr_cells = table.rows[0].cells
    headers = ["教学环节", "教师活动", "学生活动", "设计意图"]
    
    for i, header in enumerate(headers):
        # 表头内容赋值
        hdr_cells[i].text = header
        # 表头格式：加粗+居中+字号调整
        para = hdr_cells[i].paragraphs[0]
        para.runs[0].bold = True
        para.alignment = WD_PARAGRAPH_ALIGNMENT.CENTER
        para.runs[0].font.size = Pt(11)
        # ✅ 核心优化：python-docx 真正生效的列宽设置方式（直接cell.width无效）
        hdr_cells[i].width = widths[i]
        hdr_cells[i]._tc.get_or_add_tcPr().tcW.val = int(widths[i]/Inches(1)*914400)

    # 填充教学过程表格数据
    for step in lesson_data['process']:
        row_cells = table.add_row().cells
        # 单元格赋值
        row_cells[0].text = step['phase']
        row_cells[1].text = step['teacher']
        row_cells[2].text = step['student']
        row_cells[3].text = step['intent']
        # 内容单元格格式：字号+行距统一
        for cell in row_cells:
            para = cell.paragraphs[0]
            para.runs[0].font.size = Pt(10.5)
            para.paragraph_format.line_spacing = 1.2
            # 统一列宽
            for i, cell in enumerate(row_cells):
                cell._tc.get_or_add_tcPr().tcW.val = int(widths[i]/Inches(1)*914400)

    doc.add_page_break()  # 每课分页，排版更清晰

